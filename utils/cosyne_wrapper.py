import torch as pt
from evotorch_custom import Problem
from evotorch_custom.algorithms import Cosyne

class CosyneWrapper:
    def __init__(self,
                 feature_grid,
                 map_depth,
                 n_solutions,
                 solution_length,
                 evals_size,
                 initial_param_bounds = (-pt.pi, pt.pi),
                 device='cpu',
                 ):
        
        assert n_solutions % 3 == 0
        popsize = n_solutions // 3
        
        self.searcher = Cosyne(
            self._init_problem(solution_length, initial_param_bounds, evals_size, device),
            evaluate = False, # don't evaluate on it's own
            permute_all = False, # wether to recombine all solutions
            ## Mutation ##
            mutation_stdev = 0.6, # gausian mutation
            mutation_probability = 0.1,
            ## Crossover ##
            eta = 1, # simulated binary crossover
            tournament_size = 2, # tournament selection
            num_elites = 1, # best solution from previous population is always used as parent for new population
            popsize = popsize, # when using map_elites, the population size is 3*popsize
            # crossover selects 1*popsize parents and generates 2*popsize offspring from them
            # in addition 1*popsize solutions are generated by permutatating the parents
            
            ## MAPElites ##
            use_map_elites = True,
            feature_grid = feature_grid,
            map_depth = map_depth,
            map_selector = 'improvement', # 'rand_local', # selects bins around best imporving bin/random bin
            try_cutoff = 2, # number of times a solution can be selected as a parent before it is forced out by any new solution coming into the cell regardless of fitness
            ejector = 'challenge', # new solutions need to be better than worst existing (or worst existing has too many tries)
            re_evaluate = False, # no reevaluation of chalenged solutions 
            selector = 'all', # allow multiple solutions from same bin to be selected
            
            # not relevant when using map elites
            popsize_cosyne = 0, 
            perc_parents = None,
            )

    def _init_problem(self, solution_length, initial_bounds, eval_data_length, device):
        """
        Shortcut for creating Problem instance.
        """
        problem = Problem('max',
                        objective_func= lambda params: exec('raise NotImplementedError("Manual evaluation")'),
                        solution_length=solution_length,
                        initial_bounds=initial_bounds,
                        eval_data_length=eval_data_length,
                        num_actors=0,
                        eval_dtype='float64',
                        device=device)
        return problem

    def set_evals(self, evals):
        pop = self.searcher._population
        if len(pop) < len(evals):
            print(f"Warning: Only {len(pop)} of {len(evals)} set")
        pop.set_evals(evals[:len(pop)])

    def initial_params(self):
        params = self.searcher.population.access_values()
        return params
    
    def step(self, evals):
        self.searcher.step()
        params = self.searcher.population.access_values()
        return params

    def get_map_evals(self):
        x = pt.stack([self.searcher.map._map[k].evals for k in range(self.searcher.map._depth)], dim=1)
        bin_size = self.searcher.map._bin_size
        return x.view((bin_size, bin_size) + x.shape[1:])
    
    def get_map_solutions(self):
        x = pt.stack([self.searcher.map._map[k].values for k in range(self.searcher.map._depth)], dim=1)
        bin_size = self.searcher.map._bin_size
        return x.view((bin_size, bin_size) + x.shape[1:])